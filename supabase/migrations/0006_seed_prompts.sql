## slug 규칙 — 멱등성의 핵심

같은 개념은 **언제 다시 컴파일해도 같은 slug**여야 합니다. 시스템이 `(워크스페이스, slug)`로 upsert하므로, slug가 흔들리면 같은 주제의 문서가 중복 생성됩니다.

- 소문자, 공백은 하이픈. 한국어는 그대로 두되 조사·수식어는 빼고 핵심어만
- `기존 위키 slug` 목록에 이미 있는 주제라면 **반드시 그 slug를 그대로 재사용**하세요. 새 slug를 만들면 중복 문서가 됩니다
- 예: `retrieval-augmented-generation`, `사내-배포-절차`, `openrouter`

## 문서 간 링크

본문에서 다른 문서를 가리킬 때는 `[[slug]]`로 씁니다. **아직 없는 문서를 가리켜도 됩니다** — 시스템이 미해결 링크로 기록했다가 그 문서가 생기면 자동으로 잇습니다. 오히려 "이 다음에 만들 문서"를 드러내는 신호라 유용합니다.

